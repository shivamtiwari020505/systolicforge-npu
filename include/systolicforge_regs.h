#ifndef SYSTOLICFORGE_REGS_H
#define SYSTOLICFORGE_REGS_H

/* 32-bit AXI4-Lite register offsets. */
#define SYSTOLICFORGE_REG_ID                 0x00u
#define SYSTOLICFORGE_REG_VERSION            0x04u
#define SYSTOLICFORGE_REG_CONTROL            0x08u
#define SYSTOLICFORGE_REG_STATUS             0x0cu
#define SYSTOLICFORGE_REG_IRQ_ENABLE         0x10u
#define SYSTOLICFORGE_REG_IRQ_STATUS         0x14u
#define SYSTOLICFORGE_REG_PROGRAM_ADDR       0x20u
#define SYSTOLICFORGE_REG_PROGRAM_DATA_0     0x24u
#define SYSTOLICFORGE_REG_PROGRAM_DATA_1     0x28u
#define SYSTOLICFORGE_REG_PROGRAM_DATA_2     0x2cu
#define SYSTOLICFORGE_REG_PROGRAM_DATA_3     0x30u
#define SYSTOLICFORGE_REG_PROGRAM_COMMIT     0x34u
#define SYSTOLICFORGE_REG_DMA_CONFIG         0x40u
#define SYSTOLICFORGE_REG_DMA_LOCAL_ADDR     0x44u
#define SYSTOLICFORGE_REG_DMA_EXT_ADDR       0x48u
#define SYSTOLICFORGE_REG_DMA_LENGTH         0x4cu
#define SYSTOLICFORGE_REG_DMA_SUBMIT         0x50u

#define SYSTOLICFORGE_ID_VALUE               0x53464e50u
#define SYSTOLICFORGE_VERSION_VALUE          0x00010000u

#define SYSTOLICFORGE_CONTROL_START          (1u << 0)

#define SYSTOLICFORGE_STATUS_COMPUTE_BUSY    (1u << 0)
#define SYSTOLICFORGE_STATUS_DMA_BUSY        (1u << 1)
#define SYSTOLICFORGE_STATUS_FAULT           (1u << 2)
#define SYSTOLICFORGE_STATUS_IRQ             (1u << 3)
#define SYSTOLICFORGE_STATUS_FAULT_CODE_SHIFT 4u
#define SYSTOLICFORGE_STATUS_FAULT_CODE_MASK (0x0fu << SYSTOLICFORGE_STATUS_FAULT_CODE_SHIFT)
#define SYSTOLICFORGE_STATUS_DMA_READY       (1u << 8)

#define SYSTOLICFORGE_IRQ_COMPUTE_DONE       (1u << 0)
#define SYSTOLICFORGE_IRQ_DMA_DONE           (1u << 1)
#define SYSTOLICFORGE_IRQ_FAULT              (1u << 2)
#define SYSTOLICFORGE_IRQ_ALL                0x07u

#define SYSTOLICFORGE_PROGRAM_COMMIT         (1u << 0)

#define SYSTOLICFORGE_DMA_TO_EXTERNAL        0u
#define SYSTOLICFORGE_DMA_TO_LOCAL           (1u << 0)
#define SYSTOLICFORGE_DMA_MEMORY_SHIFT       1u
#define SYSTOLICFORGE_DMA_MEMORY_MASK        (0x03u << SYSTOLICFORGE_DMA_MEMORY_SHIFT)
#define SYSTOLICFORGE_DMA_MEMORY_A           (0u << SYSTOLICFORGE_DMA_MEMORY_SHIFT)
#define SYSTOLICFORGE_DMA_MEMORY_B           (1u << SYSTOLICFORGE_DMA_MEMORY_SHIFT)
#define SYSTOLICFORGE_DMA_MEMORY_C           (2u << SYSTOLICFORGE_DMA_MEMORY_SHIFT)
#define SYSTOLICFORGE_DMA_SUBMIT             (1u << 0)

#define SYSTOLICFORGE_FAULT_NONE                 0u
#define SYSTOLICFORGE_FAULT_ILLEGAL_OPCODE       1u
#define SYSTOLICFORGE_FAULT_ILLEGAL_DIMENSION    2u
#define SYSTOLICFORGE_FAULT_ADDRESS_RANGE        3u
#define SYSTOLICFORGE_FAULT_PROGRAM_OVERRUN      4u
#define SYSTOLICFORGE_FAULT_DMA_INVALID_MEMORY   5u
#define SYSTOLICFORGE_FAULT_DMA_LOCAL_RANGE      6u
#define SYSTOLICFORGE_FAULT_DMA_EXTERNAL_ADDRESS 7u

#endif
